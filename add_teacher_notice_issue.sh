#!/bin/bash
gh label create "선생님공지" --color "9333EA" --force

gh issue create --title "선생님 공지사항 기능 (담임/수업별 노출)" --label "선생님공지" --body "$(cat <<'EOF'
teacher 역할 선생님만 공지사항을 올릴 수 있는 페이지 하나 만들기.
페이지는 하나지만, 보이는 공지는 학생마다 다름 - 학생이 속한 학급/수강 중인 수업 기준으로 필터링됨.

예시:
- 11학년 샬롬반 학생 -> 담임 김진영 선생님의 "학급 공지" 보임
- 12학년 중 김진영 선생님 국어 수업 듣는 학생 -> 그 "수업 공지" 보임
- 11학년 샬롬반이라고 12학년 수업 공지가 보이면 안 됨 (실제 수강 여부로 걸러야 함)

즉 공지는 두 종류로 나뉨:
1. 담임 공지 - 학급 단위 (학생은 학급 하나에만 속함)
2. 수업 공지 - 과목 단위 (학생은 여러 수업 수강 가능, 다대다)

학생이 페이지 열면 "내 담임 학급 공지" + "내가 듣는 수업들의 공지"를 합쳐서 보여줘야 함.

TBD: 학생별 학급(담임)/수업(수강과목) 정보를 엑셀 업로드로 관리할지, 관리자가 수동 배정할지, 선생님이 직접 배정할지 아직 미정 - 결정되면 별도로 알려줄 예정.
EOF
)"
